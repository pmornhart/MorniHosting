import { execFile } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { promisify } from 'node:util';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

const run = promisify(execFile);
const SCRIPT = path.resolve(import.meta.dirname, '../../../scripts/guard.sh');
/** The fake programs must be runnable. */
const EXECUTABLE = 0o755;
/** Half an hour of checks (one per minute). */
const HALF_AN_HOUR = 30;
/** Minutes 2–10 every minute, then minutes 20 and 30. */
const RESTARTS_IN_HALF_AN_HOUR = 11;
/** The first restart comes in the second minute. */
const FIRST_RESTART = 2;
const A_FEW_MINUTES = 5;

const NETBIRD_RESOLV = '# Generated by NetBird\nnameserver 100.92.4.1\n';
const DISCONNECTED =
  'Management: Disconnected, reason: lookup netbird.example.de: i/o timeout\nSignal: Disconnected\n';
const NEEDS_LOGIN = 'Daemon status: NeedsLogin\n\nRun UP command to log in with SSO (interactive login)\n';

/** netbird: "status" from a file, every "up" written down (and it never connects). */
const FAKE_NETBIRD = `#!/usr/bin/env bash
case "$1" in
  status) cat "$FAKE_DIR/nbstatus" ;;
  up) echo up >>"$FAKE_DIR/calls"; exit 1 ;;
esac
`;
/** systemctl: a restart of NetBird puts NetBird's own DNS server back, like NetBird's restore on stop. */
const FAKE_SYSTEMCTL = `#!/usr/bin/env bash
if [[ "$1 $2" == "restart netbird" ]]; then
  echo restart >>"$FAKE_DIR/calls"
  printf '${NETBIRD_RESOLV.replaceAll('\n', '\\n')}' >"$MH_RESOLV_CONF"
fi
exit 0
`;
/** getent: only the fixed DNS servers answer (NetBird's own one cannot while NetBird is down). */
const FAKE_GETENT = `#!/usr/bin/env bash
grep -q '^nameserver 1.1.1.1' "$MH_RESOLV_CONF" && exit 0 || exit 2
`;
const FAKE_DOCKER = '#!/usr/bin/env bash\nexit 1\n';
const FAKE_SLEEP = '#!/usr/bin/env bash\nexit 0\n';

interface GuardEvent {
  readonly key: string;
  readonly status: string;
  readonly title: string;
  readonly what: string;
  readonly command?: string;
}

describe('guard.sh: NetBird stays down (Philip, 16.11.: 443 restarts in 7 hours)', () => {
  let root: string;
  let env: NodeJS.ProcessEnv;
  const file = (name: string) => path.join(root, name);
  const read = (name: string) => (fs.existsSync(file(name)) ? fs.readFileSync(file(name), 'utf8') : '');
  const calls = (what: string) =>
    read('calls')
      .split('\n')
      .filter((line) => line === what).length;
  const guard = () => run('bash', [SCRIPT, 'netbird'], { env });
  const guardTimes = async (times: number) => {
    await Array.from({ length: times }).reduce<Promise<unknown>>(
      (previous) => previous.then(guard),
      Promise.resolve(),
    );
  };
  const events = (): GuardEvent[] =>
    read('state/events-pending.jsonl')
      .split('\n')
      .filter(Boolean)
      .map((line) => JSON.parse(line) as GuardEvent);

  beforeEach(() => {
    root = fs.mkdtempSync(path.join(os.tmpdir(), 'mh-guard-netbird-'));
    const bin = file('bin');
    fs.mkdirSync(bin);
    const fakes = {
      netbird: FAKE_NETBIRD,
      systemctl: FAKE_SYSTEMCTL,
      getent: FAKE_GETENT,
      docker: FAKE_DOCKER,
      sleep: FAKE_SLEEP,
    };
    Object.entries(fakes).forEach(([name, body]) =>
      fs.writeFileSync(path.join(bin, name), body, { mode: EXECUTABLE }),
    );
    fs.writeFileSync(file('resolv.conf'), 'nameserver 1.1.1.1\nnameserver 9.9.9.9\n');
    env = {
      PATH: `${bin}:${process.env.PATH ?? ''}`,
      FAKE_DIR: root,
      MH_RESOLV_CONF: file('resolv.conf'),
      MH_GUARD_STATE_DIR: file('state'),
      MH_GUARD_LOG: file('guard.log'),
    };
  });
  afterEach(() => fs.rmSync(root, { recursive: true, force: true }));

  it('restarts quickly at first, then only every 10 minutes – and says why', async () => {
    fs.writeFileSync(file('nbstatus'), DISCONNECTED);
    await guardTimes(HALF_AN_HOUR);
    expect(calls('restart')).toBe(RESTARTS_IN_HALF_AN_HOUR);
    expect(read('guard.log')).toContain('reason: lookup netbird.example.de: i/o timeout');
    const seen = events();
    expect(seen.map((e) => `${e.key} ${e.status}`)).toEqual(['netbird fixing', 'netbird action']);
    expect(seen[1]?.what).toContain(
      'NetBird sagt: Management: Disconnected, reason: lookup netbird.example.de',
    );
  });

  it('a NetBird restart must not leave its dead DNS server behind', async () => {
    fs.writeFileSync(file('nbstatus'), DISCONNECTED);
    await guardTimes(FIRST_RESTART);
    expect(calls('restart')).toBe(1);
    // NetBird put its own server back on restart – the guard took the fixed ones again right away, quietly.
    expect(read('resolv.conf')).toContain('nameserver 1.1.1.1');
    expect(events().map((e) => e.key)).toEqual(['netbird']);
  });

  it('when the login has expired: no restarts (they cannot help), one message with the way out', async () => {
    fs.writeFileSync(file('nbstatus'), NEEDS_LOGIN);
    await guardTimes(A_FEW_MINUTES);
    expect(calls('restart')).toBe(0);
    expect(calls('up')).toBe(0);
    const seen = events();
    expect(seen).toHaveLength(1);
    expect(seen[0]).toMatchObject({ key: 'netbird', status: 'action', title: 'NetBird ist abgemeldet' });
    expect(seen[0]?.command).toBe('netbird up --setup-key <DEIN-SETUP-KEY>');
  });
});
