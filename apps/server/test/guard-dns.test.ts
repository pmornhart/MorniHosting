import { execFile } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { promisify } from 'node:util';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

const run = promisify(execFile);
const SCRIPT = path.resolve(import.meta.dirname, '../../../scripts/guard.sh');

/** getent that answers depending on a file: up, down, or only once the fixed servers are written. */
const FAKE_GETENT = `#!/usr/bin/env bash
mode="$(cat "$FAKE_DIR/dns")"
case "$mode" in
  up) exit 0 ;;
  down) exit 2 ;;
  fallback) grep -q '^nameserver 1.1.1.1' "$MH_RESOLV_CONF" && exit 0 || exit 2 ;;
esac
exit 2
`;
/** No Docker in the test: the events stay in the guard's own file. */
const FAKE_DOCKER = '#!/usr/bin/env bash\nexit 1\n';
/** The fake programs must be runnable. */
const EXECUTABLE = 0o755;

const NETBIRD_RESOLV = '# Generated by NetBird\nnameserver 100.92.4.1\nsearch netbird.cloud\n';
const FIXED_RESOLV =
  '# MorniHosting NetBird-Wächter: feste DNS-Server\nnameserver 1.1.1.1\nnameserver 9.9.9.9\n';

interface GuardEvent {
  readonly key: string;
  readonly status: string;
  readonly title: string;
  readonly what: string;
  readonly command?: string;
}

describe('guard.sh: DNS (Philip: "DNS repariert" every 30 minutes)', () => {
  let root: string;
  let env: NodeJS.ProcessEnv;
  const resolv = () => path.join(root, 'resolv.conf');
  const dns = (mode: 'up' | 'down' | 'fallback') => fs.writeFileSync(path.join(root, 'dns'), mode);
  const guard = () => run('bash', [SCRIPT, 'dns'], { env });
  const events = (): GuardEvent[] => {
    const file = path.join(root, 'state', 'events-pending.jsonl');
    if (!fs.existsSync(file)) return [];
    return fs
      .readFileSync(file, 'utf8')
      .split('\n')
      .filter(Boolean)
      .map((line) => JSON.parse(line) as GuardEvent);
  };

  beforeEach(() => {
    root = fs.mkdtempSync(path.join(os.tmpdir(), 'mh-guard-'));
    const bin = path.join(root, 'bin');
    fs.mkdirSync(bin);
    fs.writeFileSync(path.join(bin, 'getent'), FAKE_GETENT, { mode: EXECUTABLE });
    fs.writeFileSync(path.join(bin, 'docker'), FAKE_DOCKER, { mode: EXECUTABLE });
    env = {
      PATH: `${bin}:${process.env.PATH ?? ''}`,
      FAKE_DIR: root,
      MH_RESOLV_CONF: resolv(),
      MH_GUARD_STATE_DIR: path.join(root, 'state'),
      MH_GUARD_LOG: path.join(root, 'guard.log'),
    };
  });
  afterEach(() => fs.rmSync(root, { recursive: true, force: true }));

  it('does nothing while DNS works', async () => {
    fs.writeFileSync(resolv(), NETBIRD_RESOLV);
    dns('up');
    await guard();
    expect(fs.readFileSync(resolv(), 'utf8')).toBe(NETBIRD_RESOLV);
    expect(events()).toEqual([]);
  });

  it('waits one check, then writes fixed servers and says who had set what', async () => {
    fs.writeFileSync(resolv(), NETBIRD_RESOLV);
    dns('fallback');
    await guard();
    expect(fs.readFileSync(resolv(), 'utf8')).toBe(NETBIRD_RESOLV);
    expect(events()).toEqual([]);
    await guard();
    expect(fs.readFileSync(resolv(), 'utf8')).toContain('nameserver 1.1.1.1');
    expect(fs.existsSync(path.join(root, '.pve-ignore.resolv.conf'))).toBe(true);
    const [fixed] = events();
    expect(fixed).toMatchObject({ key: 'dns', status: 'fixed', title: 'DNS repariert' });
    expect(fixed?.what).toContain('100.92.4.1');
    expect(fixed?.what).toContain('NetBird');
  });

  it('never says "repariert" when the fixed servers were already there – one message, then "geht wieder"', async () => {
    fs.writeFileSync(resolv(), FIXED_RESOLV);
    dns('down');
    await guard();
    await guard();
    await guard();
    await guard();
    expect(fs.readFileSync(resolv(), 'utf8')).toBe(FIXED_RESOLV);
    expect(events().map((e) => `${e.key} ${e.status}`)).toEqual(['dns:down action']);
    dns('up');
    await guard();
    expect(events().map((e) => `${e.key} ${e.status}`)).toEqual(['dns:down action', 'dns:down ok']);
  });

  it('a single slow answer is no outage', async () => {
    fs.writeFileSync(resolv(), FIXED_RESOLV);
    dns('down');
    await guard();
    dns('up');
    await guard();
    dns('down');
    await guard();
    dns('up');
    await guard();
    expect(events()).toEqual([]);
  });

  it('when NetBird keeps resetting DNS: the third time one message with the way out, then quiet', async () => {
    dns('fallback');
    const cycle = async () => {
      fs.writeFileSync(resolv(), NETBIRD_RESOLV);
      await guard();
      await guard();
    };
    await cycle();
    await cycle();
    await cycle();
    await cycle();
    await cycle();
    const seen = events();
    expect(seen.map((e) => `${e.key} ${e.status}`)).toEqual([
      'dns fixed',
      'dns fixed',
      'dns:flapping action',
    ]);
    expect(seen[2]?.command).toBe('netbird down && netbird up --disable-dns');
    // It still repairs every time, it just stops writing about it.
    expect(fs.readFileSync(resolv(), 'utf8')).toContain('nameserver 1.1.1.1');
  });
});
